#!/usr/bin/env bash
# Regenerates /etc/nginx/snippets/cloudflare-realip.conf from Cloudflare's published IP lists and
# reloads Nginx if the list changed. Run as root (weekly via afriva-cloudflare-ips.timer).
set -euo pipefail

OUT="${1:-/etc/nginx/snippets/cloudflare-realip.conf}"
tmp="$(mktemp)"
trap 'rm -f "$tmp" "$tmp.v4" "$tmp.v6"' EXIT

curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 -o "$tmp.v4"
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 -o "$tmp.v6"

# Sanity checks: refuse empty or malformed lists so a bad download never removes trusted ranges.
grep -Eqv '^[0-9.]+/[0-9]+$' <(grep -v '^$' "$tmp.v4") && { echo "unexpected IPv4 list" >&2; exit 1; }
grep -Eqv '^[0-9a-f:]+/[0-9]+$' <(grep -v '^$' "$tmp.v6") && { echo "unexpected IPv6 list" >&2; exit 1; }
[ "$(grep -c . "$tmp.v4")" -ge 5 ] || { echo "IPv4 list too short" >&2; exit 1; }

{
    echo "# Generated by update-cloudflare-ips.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ'). Do not edit."
    echo "# IPv4"
    grep . "$tmp.v4" | sed 's/^/set_real_ip_from /; s/$/;/'
    echo "# IPv6"
    grep . "$tmp.v6" | sed 's/^/set_real_ip_from /; s/$/;/'
    echo
    echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"

if [ -f "$OUT" ] && diff -q <(grep -v '^# Generated' "$OUT") <(grep -v '^# Generated' "$tmp") > /dev/null; then
    echo "Cloudflare ranges unchanged"
    exit 0
fi

backup=""
if [ -f "$OUT" ]; then
    backup="$OUT.bak"
    cp "$OUT" "$backup"
fi
install -m 0644 "$tmp" "$OUT"
if nginx -t 2> /dev/null; then
    systemctl reload nginx
    echo "Cloudflare ranges updated and Nginx reloaded"
else
    echo "nginx -t failed with the new list; restoring the previous file" >&2
    [ -n "$backup" ] && cp "$backup" "$OUT"
    exit 1
fi
